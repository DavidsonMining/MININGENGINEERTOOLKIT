# TOPIC SEARCH FUNCTION
# ============================================================

def find_topic_answer(question):
    """
    Find a suitable answer for broader academic topics.

    More specific phrases are checked first so that:
        'first law of thermodynamics'
    is not incorrectly matched as:
        'thermodynamics'
    """

    q = question.lower().strip()

    q = q.replace("what's", "what is")
    q = q.replace("whats", "what is")

    # Check longer and more specific topics first.
    specific_topics = sorted(
        TOPIC_KNOWLEDGE.keys(),
        key=len,
        reverse=True
    )

    for topic in specific_topics:

        if topic in q:
            return TOPIC_KNOWLEDGE[topic]

    return None
